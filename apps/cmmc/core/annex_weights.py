NON_SCORABLE = frozenset({"3.12.4"})


def requirement_id(control_id: str) -> str:
    return control_id.split("-", 1)[1]


def is_sprs_scorable(control_id: str) -> bool:
    return requirement_id(control_id) not in NON_SCORABLE


def annex_weight(control_id: str) -> int:
    """Annex A subtractor; 0 for non-scorable 3.12.4."""
    rid = requirement_id(control_id)
    if rid in NON_SCORABLE:
        return 0
    return ANNEX_WEIGHTS[rid]


def apply_annex_weights(framework: dict) -> None:
    for cid in framework:
        framework[cid]["weight"] = annex_weight(cid)
